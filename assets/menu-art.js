function drawMenuArt(ctx, id) {
  const {colors, rows} = MENU_ART[id];
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] === '.') continue;
      ctx.fillStyle = colors[row.charCodeAt(x) - 65];
      ctx.fillRect(x, y, 1, 1);
    }
  });
}
