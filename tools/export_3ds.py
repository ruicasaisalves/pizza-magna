#!/usr/bin/env python3
"""Exports the toppings atlas (assets/ingredients.js) to the 3DS port: 3ds/game/gfx/atlas*.png and 3ds/game/atlas.lua.

The 3DS takes textures of at most 1024x1024, so the frames are packed again into 1024x1024 pages.
Turning pieces (<id>_n) are written already turned and with their shadow, as <id>_q0..q3, the same as
turned() in index.html (quarter turns clockwise, shadow rgba(60,10,4,.43) 2 px down-right).
Also writes the 48x48 icon for the bundler (3ds/icon.png). Run: python3 tools/export_3ds.py
"""
import base64, io, os, re
from PIL import Image

ROOT = os.path.join(os.path.dirname(__file__), '..')
OUT = os.path.join(ROOT, '3ds', 'game')
PAGE = 1024

src = open(os.path.join(ROOT, 'assets', 'ingredients.js')).read()
atlas = Image.open(io.BytesIO(base64.b64decode(re.search(r'src:"data:image/png;base64,([^"]+)"', src).group(1)))).convert('RGBA')
frames = {k: tuple(map(int, v)) for k, *v in re.findall(r'^\s+(\w+):\[(\d+),(\d+),(\d+),(\d+)\]', src, re.M)}
pizza = int(re.search(r'pizza:(\d+)', src).group(1))

def turned(img, q):
    r = img.transpose([None, Image.ROTATE_270, Image.ROTATE_180, Image.ROTATE_90][q]) if q else img
    a = r.getchannel('A').point(lambda v: round(v * .43))
    shadow = Image.new('RGBA', r.size, (60, 10, 4, 0)); shadow.putalpha(a)
    out = Image.new('RGBA', (r.width + 2, r.height + 2))
    out.alpha_composite(shadow, (2, 2)); out.alpha_composite(r, (0, 0))
    return out

sprites = {}
for k, (x, y, w, h) in frames.items():
    img = atlas.crop((x, y, x + w, y + h))
    if k.endswith('_n'):
        for q in range(4): sprites[k[:-2] + '_q' + str(q)] = turned(img, q)
    else:
        sprites[k] = img

# shelf packing, tallest first, 1 px gap
pages, placed = [], {}
order = sorted(sprites, key=lambda k: (-sprites[k].height, -sprites[k].width, k))
cx = cy = shelf = 0
cur = None
for k in order:
    im = sprites[k]
    if cur is None or cx + im.width > PAGE:
        cx, cy, shelf = 0, cy + shelf + 1, 0
    if cur is None or cy + im.height > PAGE:
        cur = Image.new('RGBA', (PAGE, PAGE)); pages.append(cur); cx = cy = shelf = 0
    cur.paste(im, (cx, cy)); placed[k] = (len(pages), cx, cy, im.width, im.height)
    cx += im.width + 1; shelf = max(shelf, im.height)

os.makedirs(os.path.join(OUT, 'gfx'), exist_ok=True)
for f in os.listdir(os.path.join(OUT, 'gfx')):
    if re.match(r'atlas\d+\.png$', f): os.remove(os.path.join(OUT, 'gfx', f))
for i, p in enumerate(pages, 1):
    p.save(os.path.join(OUT, 'gfx', f'atlas{i}.png'), optimize=True)
with open(os.path.join(OUT, 'atlas.lua'), 'w') as f:
    f.write('-- Generated by tools/export_3ds.py from assets/ingredients.js. Do not edit by hand.\n')
    f.write(f'return {{pizza={pizza},pages={len(pages)},frames={{\n')
    for k in sorted(placed): f.write(' %s={%d,%d,%d,%d,%d},\n' % ((k,) + placed[k]))
    f.write('}}\n')
Image.open(os.path.join(ROOT, 'assets', 'icon-192.png')).convert('RGBA').resize((48, 48), Image.LANCZOS).save(os.path.join(ROOT, '3ds', 'icon.png'))
print(f'{len(placed)} sprites in {len(pages)} pages of {PAGE}x{PAGE}')
