#!/usr/bin/env node
/* Exports the game data from index.html to the 3DS port (3ds/game/data.lua), so both share one source.
   Runs the LANGUAGE and DATA sections and the kitchen weight constants in a sandbox and writes them as Lua.
   Run again after changing toppings, combos, prices or I18N: node tools/export_3ds.js */
const fs=require('fs'),path=require('path'),vm=require('vm');
const root=path.join(__dirname,'..'),html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const cut=(a,b)=>{const i=html.indexOf(a),j=html.indexOf(b,i);if(i<0||j<0)throw new Error('marker not found: '+a+' / '+b);return html.slice(i,j)};
const src=[
  cut('/* ================= LANGUAGE','/* ================= HELPERS'),
  cut('// Prices: a plain thin pizza','const WD_EN='),
  cut('const GRATED_W=','const fmtG='),
  cut('const CATS=','function ingCat'),
  cut('const CAT_ICON=','function pantryHTML'),
  'this.OUT={I18N,DOUGHS,SAUCES,ING,PACKS,COMBOS,SEG,CASA:[...CASA],EXOTIC:[...EXOTIC],WEEK_BONUS,VALUE_CAP,APPEAL_W,'+
  'GRATED_W,BIG_SHRED:[...BIG_SHRED],SHRED_W,WHOLE_W,CENTRED:[...CENTRED],GRAMS,GRAMS_GRATED,CATS,HERBS,FAV,EXTRAS,CAT_ICON,'+
  'BASE_PRICE,MARKUP};'
].join('\n');
const ctx={navigator:{languages:['en'],language:'en'},localStorage:{getItem:()=>null,setItem(){}},
  document:{documentElement:{lang:''},querySelectorAll:()=>[]},window:{},console};
vm.createContext(ctx);vm.runInContext(src.replace(/^(const|let) /gm,'var '),ctx);
const O=ctx.OUT;
// the names are filled from I18N at runtime in the 3DS game; keep the data language-free
for(const k in O.ING)delete O.ING[k].n;for(const k in O.DOUGHS)delete O.DOUGHS[k].n;for(const k in O.SAUCES)delete O.SAUCES[k].n;
for(const k in O.SEG)delete O.SEG[k].n;for(const c of O.COMBOS){delete c.n;delete c.quote}
O.ING_ORDER=Object.keys(O.ING);O.DOUGH_ORDER=Object.keys(O.DOUGHS);O.SAUCE_ORDER=Object.keys(O.SAUCES);O.SEG_ORDER=Object.keys(O.SEG);
const str=s=>'"'+String(s).replace(/\\/g,'\\\\').replace(/"/g,'\\"').replace(/\n/g,'\\n')+'"';
const key=k=>/^[A-Za-z_][A-Za-z0-9_]*$/.test(k)&&!['and','or','not','end','if','then','do','for','in','local','function','nil','true','false','repeat','until','while','return','break','else','elseif'].includes(k)?k:'['+str(k)+']';
function lua(v,ind=''){
  if(v===null||v===undefined)return 'nil';
  if(typeof v==='number'||typeof v==='boolean')return String(v);
  if(typeof v==='string')return str(v);
  if(Array.isArray(v))return '{'+v.map(x=>lua(x,ind)).join(',')+'}';
  const ks=Object.keys(v),inner=ind+' ',long=ks.length>6;
  return '{'+ks.map(k=>(long?'\n'+inner:'')+key(k)+'='+lua(v[k],inner)).join(',')+(long?'\n'+ind:'')+'}';
}
let out='-- Generated by tools/export_3ds.js from index.html. Do not edit by hand.\nlocal D={}\n';
for(const k of Object.keys(O))out+='D.'+k+'='+lua(O[k])+'\n';
out+='return D\n';
fs.writeFileSync(path.join(root,'3ds/game/data.lua'),out);
console.log('3ds/game/data.lua:',out.length,'bytes,',O.ING_ORDER.length,'toppings,',O.COMBOS.length,'combos');
