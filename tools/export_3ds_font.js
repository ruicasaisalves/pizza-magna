#!/usr/bin/env node
/* The 3DS port's letters: Nunito (tools/fonts/nunito.ttf, SIL Open Font License) drawn once, anti-aliased, at the exact
   pixel sizes the port uses, into 3ds/game/gfx/font.png, with each glyph's place, advance and offset in
   3ds/game/fontdata.lua. bfont.lua draws text from them, so letters stay sharp on the console (its system font, scaled
   down, was blurred, and LÖVE Potion has no image fonts on the 3DS).
   Uses the Chromium that Playwright drives. Run after adding a size or a character:
   node tools/export_3ds_font.js */
const {chromium}=require('playwright');
const fs=require('fs'),path=require('path');
const root=path.join(__dirname,'..');
// name: [pixel size, weight]
const SIZES={tiny:[12,800],small:[13,700],body:[16,700],big:[28,800]};
const CH=[];for(let c=32;c<127;c++)CH.push(String.fromCharCode(c));
for(const c of '·ºªÀÁÂÃÇÈÉÊÍÑÓÔÕÖ×ÙÚÜàáâãçèéêíñóôõöùúü—–’‘“”…›‹←→↑↓≈★☆€✓✚♥⛔')CH.push(c);
(async()=>{
  const b=await chromium.launch(),pg=await b.newPage();
  const font='data:font/ttf;base64,'+fs.readFileSync(path.join(root,'tools/fonts/nunito.ttf')).toString('base64');
  await pg.setContent(`<html><head><style>@font-face{font-family:N;src:url(${font});font-weight:200 1000}</style></head><body><canvas id=c width=512 height=512></canvas></body></html>`);
  const out=await pg.evaluate(async([SIZES,CH])=>{
    for(const k in SIZES)await document.fonts.load(SIZES[k][1]+' '+SIZES[k][0]+'px N');
    const c=document.getElementById('c'),x=c.getContext('2d');const meta={};let cx=0,cy=0,rowH=0;
    for(const k in SIZES){
      const [sz,wt]=SIZES[k];x.font=wt+' '+sz+'px N';
      const asc=Math.ceil(sz*1.02),h=Math.ceil(sz*1.36),g={};
      for(const ch of CH){
        const m=x.measureText(ch),l=Math.floor(-m.actualBoundingBoxLeft),r=Math.ceil(m.actualBoundingBoxRight),w=Math.max(1,r-l+2);
        if(cx+w>512){cx=0;cy+=rowH+1;rowH=0}
        x.fillStyle='#fff';x.textBaseline='alphabetic';x.fillText(ch,cx-l+1,cy+asc);
        g[ch]=[cx,cy,w,h,Math.round(m.width*100)/100,l-1];cx+=w+1;rowH=Math.max(rowH,h);
      }
      meta[k]={h,line:Math.round(sz*1.25),g};cx=0;cy+=rowH+2;rowH=0;
    }
    if(cy>512)throw new Error('font.png is full');
    // a little more ink on the soft edges, so thin strokes read on the console
    const d=x.getImageData(0,0,512,512);for(let i=3;i<d.data.length;i+=4)d.data[i]=Math.round(255*Math.min(1,Math.pow(d.data[i]/255,.8)));x.putImageData(d,0,0);
    return {meta,png:c.toDataURL()};
  },[SIZES,CH]);
  await b.close();
  fs.writeFileSync(path.join(root,'3ds/game/gfx/font.png'),Buffer.from(out.png.split(',')[1],'base64'));
  const lua=v=>Array.isArray(v)?'{'+v.join(',')+'}':'{'+Object.entries(v).map(([k,x])=>'['+JSON.stringify(k)+']='+(typeof x==='object'?lua(x):x)).join(',')+'}';
  fs.writeFileSync(path.join(root,'3ds/game/fontdata.lua'),'-- Generated by tools/export_3ds_font.js (Nunito, SIL Open Font License). Do not edit by hand.\n-- size name = {h = cell height, line = line height, g = {[char] = {x, y, w, h, advance, left}}} in gfx/font.png\nreturn '+lua(out.meta)+'\n');
  console.log('3ds/game/gfx/font.png and fontdata.lua:',CH.length,'characters,',Object.keys(SIZES).join(', '));
})();
